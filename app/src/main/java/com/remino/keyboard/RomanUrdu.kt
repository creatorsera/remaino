package com.remino.keyboard

/**
 * Roman Urdu to Urdu script. About 741 common words come from a built-in list, so the
 * English keyboard can offer the Urdu spelling without switching languages.
 * Only exact matches are offered, so nothing is guessed.
 */
object RomanUrdu {
    private val dictionary: Map<String, String> by lazy {
        val map = LinkedHashMap<String, String>()
        for (line in WORDS.lines()) {
            val parts = line.trim().split("=")
            if (parts.size == 2 && parts[0].isNotEmpty()) map[parts[0]] = parts[1]
        }
        map
    }

    val size: Int get() = dictionary.size

    /** The Urdu spelling of an exact Roman word, or null. */
    fun lookup(word: String): String? = dictionary[word.trim().lowercase()]

    /** Roman words that start with the typed prefix (at least three letters). */
    fun complete(prefix: String, limit: Int): List<String> {
        val p = prefix.trim().lowercase()
        if (p.length < 3) return emptyList()
        return dictionary.keys.filter { it.startsWith(p) && it != p }.take(limit)
    }

